                    <!-- Airline Cancellations -->
                    <section id="airline-cancellations">

                        <h2>
                            Airline Ticket Cancellations
                        </h2>

                        <p>
                            Airline tickets are subject to the fare rules and
                            cancellation conditions established by the applicable
                            airline. Before requesting a cancellation, travelers
                            should review the fare conditions associated with their
                            ticket.
                        </p>

                        <h3>
                            Non-Refundable Tickets
                        </h3>

                        <p>
                            If an airline ticket is identified as non-refundable,
                            a voluntary cancellation generally does not qualify
                            for a cash refund. Depending on the airline's rules,
                            the traveler may instead receive an airline credit,
                            eCredit, or other form of travel credit.
                        </p>

                        <h3>
                            Refundable Tickets
                        </h3>

                        <p>
                            Refundable tickets may qualify for a full or partial
                            refund when cancelled within the applicable time period
                            and in accordance with the airline's fare rules.
                        </p>

                        <h3>
                            24-Hour Cancellation
                        </h3>

                        <p>
                            Certain airline bookings may qualify for cancellation
                            within 24 hours of purchase without a cancellation
                            penalty, subject to applicable airline policies,
                            booking conditions, and federal or other applicable
                            regulations.
                        </p>

                        <div class="notice-box">

                            <i class="fa-solid fa-triangle-exclamation"></i>

                            <p>
                                <strong>Please note:</strong>
                                The 24-hour cancellation provision may not apply
                                to every itinerary, supplier, fare, or booking
                                circumstance. Eligibility will depend on the
                                applicable rules governing your reservation.
                            </p>

                        </div>

                    </section>


                    <!-- Hotels / Cars -->
                    <section id="hotel-car">

                        <h2>
                            Hotels, Cars &amp; Other Travel Services
                        </h2>

                        <p>
                            Cancellation and refund rules for hotels, car rentals,
                            cruises, tours, and other travel services are determined
                            primarily by the applicable supplier.
                        </p>

                        <p>
                            Some hotel and vehicle reservations may allow free
                            cancellation until a specified deadline, while other
                            reservations may be partially refundable or completely
                            non-refundable.
                        </p>

                        <p>
                            If a cancellation request is submitted after the
                            supplier's permitted cancellation period, the customer
                            may be charged a cancellation penalty or may forfeit
                            some or all of the amount paid.
                        </p>

                        <p>
                            Travelers should always review the cancellation deadline,
                            refund conditions, and applicable supplier restrictions
                            before completing a reservation.
                        </p>

                    </section>


                    <!-- Vacation Packages -->
