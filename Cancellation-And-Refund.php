                        <h2>
                            Changes &amp; Modifications
                        </h2>

                        <p>
                            Travelers may request changes to eligible reservations,
                            including travel dates, itinerary details, routing,
                            passenger information, or other booking components.
                            All requested changes are subject to supplier approval
                            and applicable fare or booking conditions.
                        </p>

                        <p>
                            Changes may result in additional charges, including
                            airline or supplier change fees, fare differences,
                            taxes, service fees, or other applicable charges.
                        </p>

                        <p>
                            Global Air Hub cannot guarantee that a requested change
                            will be available. Availability depends on the airline,
                            hotel, car rental company, cruise line, or other relevant
                            travel provider.
                        </p>

                        <h3>
                            No-Show Bookings
                        </h3>

                        <p>
                            Failure to cancel or modify a reservation before the
                            applicable deadline may be treated as a no-show. A
                            no-show may result in the loss of the ticket or service
                            value and may make the reservation ineligible for a refund
                            or future changes.
                        </p>

                    </section>


                    <!-- Refund Processing -->
                    <section id="refund-processing">

                        <h2>
                            Refund Processing
                        </h2>

                        <p>
                            Refund requests must be submitted through the applicable
                            Global Air Hub customer service channel or through the
                            supplier's designated process when instructed.
                        </p>

                        <p>
                            Once a refund request has been received, Global Air Hub
                            may need to verify the booking, review the applicable
                            fare rules, obtain approval from the supplier, and process
                            the refund according to the supplier's procedures.
                        </p>

                        <p>
                            Refund processing times vary depending on the airline,
                            supplier, payment method, banking institution, and other
                            factors. In some cases, refunds may take several weeks
                            to appear on the original payment method.
                        </p>

                        <p>
                            Unless otherwise agreed or required by applicable law,
                            approved refunds are generally returned to the original
                            form of payment used for the booking.
                        </p>

                        <div class="notice-box">

                            <i class="fa-solid fa-clock"></i>

                            <p>
                                <strong>Refund timing:</strong>
                                The time required to receive a refund is controlled
                                in part by the applicable supplier and financial
                                institution. A refund request being approved does
                                not necessarily mean that the funds will appear
                                immediately in your account.
                            </p>

                        </div>

                    </section>


