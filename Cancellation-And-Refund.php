                        <h2>
                            Vacation Packages
                        </h2>

                        <p>
                            Vacation packages may contain multiple travel components,
                            including flights, hotels, transportation, tours, cruises,
                            and other services.
                        </p>

                        <p>
                            Cancellation of a package may result in separate penalties
                            or restrictions from individual suppliers. Refunds may
                            therefore be calculated after applicable charges from
                            airlines, hotels, tour operators, transportation providers,
                            or other suppliers have been deducted.
                        </p>

                        <p>
                            The refund amount and cancellation conditions for a
                            vacation package depend on the terms applicable to each
                            component included in the booking.
                        </p>

                    </section>


                    <!-- Changes -->
