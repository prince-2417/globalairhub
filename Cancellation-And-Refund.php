                        <h2>
                            Definitions
                        </h2>

                        <p>
                            For purposes of this policy, the following terms generally
                            apply:
                        </p>

                        <p>
                            <strong>Travel Services</strong> means airline tickets,
                            hotel reservations, car rentals, vacation packages,
                            cruises, tours, and other travel-related services booked
                            through Global Air Hub.
                        </p>

                        <p>
                            <strong>Supplier</strong> means an airline, hotel,
                            cruise line, car rental company, tour operator, insurance
                            provider, or other third-party travel provider responsible
                            for delivering the purchased service.
                        </p>

                        <p>
                            <strong>Non-Refundable</strong> means a fare or service
                            that is not eligible for a refund under the applicable
                            supplier rules or after a specified cancellation deadline.
                        </p>

                        <p>
                            <strong>Refundable</strong> means a fare or service that
                            may qualify for a partial or full refund when cancelled
                            according to the applicable terms and conditions.
                        </p>

