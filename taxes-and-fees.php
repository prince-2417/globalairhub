                        <p>
                            A fare difference may arise when the new flight,
                            travel date, cabin class, route, hotel, vehicle, or
                            other travel service has a higher price than the
                            original reservation.
                        </p>

                        <p>
                            In addition to any fare difference, applicable supplier
                            penalties, change fees, taxes, service fees, or other
                            charges may also apply.
                        </p>

                        <p>
                            Any applicable additional amount must generally be paid
                            before the requested change can be completed.
                        </p>

