                        </h2>

                        <p>
                            Airlines and other travel suppliers may impose their own
                            fees and charges in connection with a travel service.
                        </p>

                        <p>
                            Depending on the service purchased, these may include
                            baggage fees, seat selection fees, priority boarding
                            charges, ticketing fees, change fees, cancellation fees,
                            rebooking charges, service charges, or other optional
                            or mandatory supplier fees.
                        </p>

                        <p>
                            Some optional services may not be included in the
                            advertised base fare and may be payable separately
                            before or during travel.
                        </p>

                        <p>
                            Customers should review the applicable airline or
                            supplier conditions for additional fees associated with
                            optional services.
