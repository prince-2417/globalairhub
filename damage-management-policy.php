                    <!-- Excluded Damage -->
                    <section id="excluded-damage">

                        <h2>
                            Damage That May Not Be Covered
                        </h2>

                        <p>
                            Not every type of baggage damage will necessarily qualify
                            for compensation. Airlines may exclude certain types of
                            damage under their conditions of carriage or applicable
                            baggage policies.
                        </p>

                        <p>
                            Examples of damage that may be excluded or subject to
                            limitations can include normal wear and tear, scratches,
                            minor dents, stains, broken wheels or handles resulting
                            from ordinary use, or damage caused by improper packing.
                        </p>

                        <p>
                            Damage resulting from prohibited items, excessive baggage
                            contents, fragile items packed without appropriate protection,
                            or circumstances outside the carrier's responsibility may
                            also be excluded.
                        </p>

                        <p>
                            The actual determination of whether damage is covered will
                            depend on the applicable airline rules, evidence provided,
                            and relevant law.
                        </p>

