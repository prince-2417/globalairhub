                        <h2>
                            Reporting Damaged Baggage
                        </h2>

                        <p>
                            If your checked baggage appears to be damaged when you arrive
                            at your destination, you should report the damage to the
                            airline or its authorized baggage service representative
                            as soon as possible.
                        </p>

                        <p>
                            Where an airport baggage service desk or claims office is
                            available, travelers should report the issue before leaving
                            the airport whenever reasonably possible.
                        </p>

                        <p>
                            If the damage is discovered after leaving the airport,
                            contact the airline or applicable travel provider promptly
                            using the contact information provided with your travel
                            documents or booking confirmation.
                        </p>

                        <p>
                            Travelers should retain any baggage claim tags, receipts,
                            photographs, boarding passes, baggage reports, and other
                            documents related to the damaged item.
                        </p>

                        <div class="notice-box">

                            <i class="fa-solid fa-triangle-exclamation"></i>

                            <p>
                                <strong>Please note:</strong>
                                Global Air Hub does not determine whether an airline will
                                accept or approve a baggage damage claim. The applicable
                                airline or responsible travel provider will generally
                                determine eligibility under its own policies and applicable
                                law.
                            </p>

                        </div>

                    </section>


                    <!-- Airline Responsibility -->
                    <section id="airline-responsibility">

                        <h2>
                            Airline Responsibility
                        </h2>

                        <p>
                            Airlines are generally responsible for handling checked
                            baggage transported under their conditions of carriage.
                            Where baggage is damaged while under an airline's care,
                            the airline may review the circumstances and determine
                            whether compensation, repair, replacement, or another
                            resolution is available.
                        </p>

                        <p>
                            The airline may require the traveler to provide evidence
                            showing the condition of the baggage before and after the
                            journey, along with documentation demonstrating ownership
                            and the value of the damaged item.
                        </p>

                        <p>
                            Different airlines may apply different procedures,
                            documentation requirements, exclusions, and claim deadlines.
                            Travelers should therefore follow the instructions provided
                            by the airline handling the baggage.
                        </p>

                        <p>
                            Where multiple airlines are involved in an itinerary,
                            responsibility may depend on which carrier transported
                            the baggage and the applicable rules governing the journey.
                        </p>

                    </section>


                    <!-- Claim Process -->
                    <section id="claim-process">

                        <h2>
                            Damage Claim Process
                        </h2>

                        <p>
                            Travelers seeking assistance with damaged baggage should
                            first notify the applicable airline or baggage service
                            provider. A baggage irregularity report or similar document
                            may be issued depending on the airline's procedures.
                        </p>

                        <p>
                            Once a claim is submitted, the airline may investigate the
                            circumstances, review supporting documents, inspect the
                            damaged baggage, and determine the appropriate resolution.
                        </p>

                        <p>
                            Depending on the circumstances and applicable rules, a
                            resolution may include repair of the baggage, replacement,
                            reimbursement, travel credit, or another form of settlement.
                        </p>

                        <p>
                            Global Air Hub may provide reasonable assistance with
                            communicating booking-related information or directing
                            travelers to the appropriate airline or travel provider.
                            However, Global Air Hub does not guarantee that a claim
                            will be approved or that compensation will be provided.
                        </p>

                    </section>


