                            <li>
                                Clear photographs showing the damage.
                            </li>

                            <li>
                                Proof of ownership.
                            </li>

                            <li>
                                Original purchase receipt or other evidence of value,
                                where available.
                            </li>

                            <li>
                                Repair estimates or replacement documentation, where
                                requested.
                            </li>
                        </ul>

                        <p>
                            Travelers should provide complete and accurate information
                            and retain copies of all documents submitted in connection
                            with their claim.
                        </p>

