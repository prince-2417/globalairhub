                            Travelers should submit a damage report and any required
                            claim documentation as soon as possible after discovering
                            the damage.
                        </p>

                        <p>
                            Failure to report or submit a claim within the applicable
                            deadline may result in the claim being rejected or the
                            traveler's ability to obtain compensation being limited.
